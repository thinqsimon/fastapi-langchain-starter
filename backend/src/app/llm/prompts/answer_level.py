def with_answer_level(system_prompt: str, level: int | None, *, for_writing: bool = False) -> str:
    """페르소나 뒤에 단계 지시를 붙인다. level이 None이면 그대로 돌려준다(예전 동작).

    for_writing: 일기 초안·주간 회고처럼 형식과 분량이 정해진 글쓰기. 그 규칙이 먼저이고
    어휘·용어 풀이·설명 깊이만 단계에 맞춘다(5단계의 '간결하게'가 '자세히 쓰기'를 덮지 않게).
    """
    if level is None:
        return system_prompt
    instruction = LEVEL_INSTRUCTIONS.get(level, LEVEL_INSTRUCTIONS[DEFAULT_ANSWER_LEVEL])
    if for_writing:
        return (
            f"{system_prompt}\n\n"
            "[작성 수준] 형식과 분량은 위 지시를 그대로 따르고, "
            "어휘·용어 풀이·설명 깊이만 아래 학습자 수준에 맞추세요.\n"
            f"{instruction}"
        )
    return (
        f"{system_prompt}\n\n"
        "[답변 수준] 아래 기준에 맞춰 어휘와 설명 깊이를 조절하세요.\n"
        f"{instruction}\n"
        "학습자가 다른 수준으로 설명해 달라고 직접 요청하면 그 요청을 먼저 따르세요."
    )
